export function accountAmount(
  a: Account,
  balances: Record<string, { debit: number; credit: number }>,
) {
  const b = balances[a.code];
  if (!b) return 0;
  return ["Asset", "COGS", "Operating Expense", "Other Expense"].includes(a.type)
    ? b.debit - b.credit
    : b.credit - b.debit;
}
export function totalByType(
  accounts: Account[],
  balances: Record<string, { debit: number; credit: number }>,
  type: AccountType,
) {
  return (
    Math.round(
      accounts
        .filter((a) => a.type === type)
        .reduce((sum, a) => sum + accountAmount(a, balances), 0) * 100,
    ) / 100
  );
}
export function resolveAccount(accounts: Account[], preferred: string, legacy: string) {
  return accounts.some((a) => a.code === preferred) ? preferred : legacy;
}
export const templateCashCodes = ["10100", "10200", "10300", "10400", "1000", "1050"];
export function cashBalanceAccount(account: Account) {
  return (
    account.type === "Asset" &&
    (account.sourceAccount
      ? account.sourceAccount.type === "Bank"
      : templateCashCodes.includes(account.code))
  );
}
export function validateCoa(accounts: Account[]) {
  for (const a of accounts) {
    if (a.parentCode) {
      const parent = accounts.find((p) => p.code === a.parentCode);
      if (!parent || parent.type !== a.type)
        throw new Error("Parent account must exist in the same company and classification.");
      const visited = new Set([a.code]);
      let cursor: Account | undefined = parent;
      while (cursor) {
        if (visited.has(cursor.code)) throw new Error("Account hierarchy cannot contain cycles.");
        visited.add(cursor.code);
        const parentCode: string | undefined = cursor.parentCode;
        cursor = accounts.find((p) => p.code === parentCode);
      }
    }
    if (
      a.maturity &&
      a.maturity !== "Unclassified" &&
      (["Asset", "Liability"].includes(a.type)
        ? a.maturity === "Not Applicable"
        : a.maturity !== "Not Applicable")
    )
      throw new Error("Current/noncurrent classification applies only to assets and liabilities.");
    if (a.isContra !== undefined) {
      const debit = ["Asset", "COGS", "Operating Expense", "Other Expense"].includes(a.type);
      const expected = (a.isContra ? !debit : debit) ? "Debit" : "Credit";
      if (a.balanceType !== expected)
        throw new Error("Normal balance must match the classification and contra-account flag.");
    }
  }
}
