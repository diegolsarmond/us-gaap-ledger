import { writeFileSync } from "node:fs";
import { ledgerSchemas, ledgerTable, childTable } from "../src/lib/ledger-schema.ts";

// Generates the reviewed, standalone SQL migration from the application's explicit column map.
let sql = `-- Generated by scripts/generate-ledger-migration.mjs. Run after 017.
-- Stop application writers while applying; all conversions are transactional.
BEGIN;
-- Remove the old JSON-specific trigger before converting currency rows.
DROP TRIGGER IF EXISTS strip_live_currency_fields ON ledger_currencies;
DROP FUNCTION IF EXISTS strip_live_currency_fields();
DROP VIEW IF EXISTS customer_registration;
DROP VIEW IF EXISTS vendor_registration;
DROP VIEW IF EXISTS chart_of_accounts;
ALTER TABLE ledger_customers ALTER COLUMN source_open_balance DROP EXPRESSION IF EXISTS;
ALTER TABLE ledger_vendors ALTER COLUMN source_open_balance DROP EXPRESSION IF EXISTS;
ALTER TABLE ledger_accounts ALTER COLUMN parent_account_code DROP EXPRESSION IF EXISTS;
`;
const extract = (field, root = "data") => `${root}#>>'{${field.path.split(".").join(",")}}'`;
for (const [domain, spec] of Object.entries(ledgerSchemas)) {
  const table = ledgerTable(domain);
  const fields = spec.fields.filter((f) => f.column !== "id");
  for (const field of fields)
    sql += `ALTER TABLE ${table} ADD COLUMN IF NOT EXISTS ${field.column} ${field.type};\n`;
  for (const [collection, childFields] of Object.entries(spec.children)) {
    const child = childTable(domain, collection);
    sql += `CREATE TABLE IF NOT EXISTS ${child} (
 company_id uuid NOT NULL, parent_id text NOT NULL, position integer NOT NULL CHECK(position>=0),
 ${childFields.map((f) => `${f.column} ${f.type}${f.optional ? "" : " NOT NULL"}`).join(",\n ")},
 PRIMARY KEY(company_id,parent_id,position),
 FOREIGN KEY(company_id,parent_id) REFERENCES ${table}(company_id,id) DEFERRABLE INITIALLY DEFERRED
);\n`;
  }
  sql += `DO $migration$ BEGIN
 IF EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid='${table}'::regclass AND attname='data' AND NOT attisdropped) THEN
`;
  // Refuse unknown keys so future/custom fields cannot silently disappear.
  const keys = [
    ...new Set([...spec.fields.map((f) => f.path.split(".")[0]), ...Object.keys(spec.children)]),
  ];
  sql += ` IF EXISTS (SELECT 1 FROM ${table}, LATERAL jsonb_object_keys(data) k WHERE k <> ALL(ARRAY[${keys.map((k) => `'${k}'`).join(",")}])) THEN
 RAISE EXCEPTION 'Unmapped data fields in ${table}; migration aborted to prevent data loss'; END IF;\n`;
  sql += ` UPDATE ${table} SET ${fields.map((f) => `${f.column}=(${extract(f)})::${f.type}`).join(",\n ")};\n`;
  for (const [collection, childFields] of Object.entries(spec.children)) {
    sql += ` INSERT INTO ${childTable(domain, collection)}(company_id,parent_id,position,${childFields.map((f) => f.column).join(",")})
 SELECT company_id,id,(ordinality-1)::integer,${childFields.map((f) => (collection === "companyIds" ? `(item#>>'{}')::uuid` : `(${extract(f, "item")})::${f.type}`)).join(",")}
 FROM ${table} CROSS JOIN LATERAL jsonb_array_elements(coalesce(nullif(data->'${collection}','null'::jsonb),'[]'::jsonb)) WITH ORDINALITY a(item,ordinality);\n`;
  }
  sql += ` ALTER TABLE ${table} DROP COLUMN data;
 END IF;
END $migration$;\n`;
  for (const field of fields.filter((f) => !f.optional))
    sql += `ALTER TABLE ${table} ALTER COLUMN ${field.column} SET NOT NULL;\n`;
}
sql += `
-- Restore business constraints formerly attached to the JSON document.
CREATE UNIQUE INDEX IF NOT EXISTS ledger_customers_display_name ON ledger_customers(company_id,lower(display_name));
DO $$ BEGIN
 IF NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid='ledger_customers'::regclass AND conname='customers_name_check') THEN
 ALTER TABLE ledger_customers ADD CONSTRAINT customers_name_check CHECK(length(btrim(display_name)) BETWEEN 1 AND 120);
 ALTER TABLE ledger_vendors ADD CONSTRAINT vendors_name_check CHECK(length(btrim(display_name)) BETWEEN 1 AND 120);
 ALTER TABLE ledger_accounts ADD CONSTRAINT accounts_metadata_check CHECK(
 (maturity IS NULL OR maturity IN ('Current','Noncurrent','Not Applicable','Unclassified'))
 AND (maturity IS NULL OR maturity='Unclassified' OR CASE WHEN type IN ('Asset','Liability') THEN maturity IN ('Current','Noncurrent') ELSE maturity='Not Applicable' END)
 AND (parent_account_code IS NULL OR parent_account_code<>id));
 END IF;
END $$;
CREATE VIEW chart_of_accounts AS SELECT company_id,id AS account_code,name AS account_name,type AS account_type,
 balance_type AS normal_balance,subgroup,coalesce(maturity,'Unclassified') AS maturity,is_contra,
 coalesce(track1099,false) AS track_1099,parent_account_code,description,position FROM ledger_accounts;
CREATE VIEW customer_registration AS SELECT company_id,id,position,display_name,company_name,customer_type,
 billing_address_street AS street_address,billing_address_city AS city,billing_address_state AS state,
 billing_address_country AS country,billing_address_zip AS zip,phone,email,currency,source_open_balance,source_balance_date
 FROM ledger_customers;
CREATE VIEW vendor_registration AS SELECT company_id,id,position,display_name,company_name,street_address,
 city,state_province AS state,country,zip_code AS zip,phone,email,track1099 AS track_1099,currency,source_open_balance,source_balance_date FROM ledger_vendors;
-- Reconciliation scope already has typed columns; persist only its financial inputs here.
-- Some installations have not run 010 yet. Create the scope table if absent.
CREATE TABLE IF NOT EXISTS cash_flow_reconciliations (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), company_id uuid NOT NULL REFERENCES companies(id),
 period_start date NOT NULL, period_end date NOT NULL CHECK(period_end>=period_start),
 currency varchar(3) NOT NULL CHECK(currency IN ('USD','BRL','EUR')),
 account_id uuid REFERENCES cash_accounts(id), updated_by uuid NOT NULL REFERENCES app_users(id),
 updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE NULLS NOT DISTINCT(company_id,period_start,period_end,currency,account_id)
);
DROP TRIGGER IF EXISTS audit_cash_flow_reconciliations ON cash_flow_reconciliations;
CREATE TRIGGER audit_cash_flow_reconciliations AFTER INSERT OR UPDATE OR DELETE ON cash_flow_reconciliations
 FOR EACH ROW EXECUTE FUNCTION record_system_audit();
`;
const reconciliation = [
  "net_income",
  "depreciation",
  "receivables",
  "inventory",
  "payables",
  "taxes_payable",
  "other_adjustments",
  "balance_sheet_cash",
  "explanation",
];
for (const field of reconciliation)
  sql += `ALTER TABLE cash_flow_reconciliations ADD COLUMN IF NOT EXISTS ${field} ${field === "explanation" ? "text" : "numeric"};\n`;
sql += `DO $$ BEGIN
 IF EXISTS(SELECT 1 FROM pg_attribute WHERE attrelid='cash_flow_reconciliations'::regclass AND attname='inputs' AND NOT attisdropped) THEN
 UPDATE cash_flow_reconciliations SET ${reconciliation.map((f) => `${f}=(inputs->>'${f}')::${f === "explanation" ? "text" : "numeric"}`).join(",")};
 ALTER TABLE cash_flow_reconciliations DROP COLUMN inputs;
 END IF;
END $$;\n`;
for (const field of reconciliation)
  sql += `ALTER TABLE cash_flow_reconciliations ALTER COLUMN ${field} SET NOT NULL;\n`;
sql += "COMMIT;\n";
writeFileSync(new URL("../database/018_structured_ledger.sql", import.meta.url), sql);
